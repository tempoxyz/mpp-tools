def write_specs(root: Path, files: dict[str, str]) -> Path:
    for relative, text in files.items():
        path = root / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    return root


class ExtractTests(unittest.TestCase):
    def setUp(self) -> None:
        self.directory = tempfile.TemporaryDirectory()
        self.root = Path(self.directory.name)
        self.path = self.root / "draft-tempo-charge-00.md"
        self.path.write_text(SPEC, encoding="utf-8")

    def tearDown(self) -> None:
        self.directory.cleanup()

    def test_unplaceable_rule_gives_up_within_budget(self) -> None:
        # Every word of the source is the rule's first word, so each window has thousands
        # of candidates and none matches: without a budget, find is quadratic.
        source = gap_report.SourceLines("MUST " * 20000)
        start = time.monotonic()
        self.assertIsNone(source.find(["MUST"] * 11 + ["verify"], 0))
        self.assertLess(time.monotonic() - start, 1.0)
        self.assertEqual(source.locate("MUST " * 11 + "verify", 7), 7)

    def test_container_render_forwards_safe_mode(self) -> None:
        # The docker CLI does not pass its environment into the container, so the render
        # command forwards each RENDER_ENV variable itself.
        docker = KramdownRfc(["docker", "run", "--rm", "-i", "img", "kramdown-rfc"])
        flags = [flag for name in gap_report.RENDER_ENV for flag in ("-e", name)]
        self.assertEqual(
            docker.render_command(),
            ["docker", "run", *flags, "--rm", "-i", "img", "kramdown-rfc"],
        )
        self.assertEqual(KramdownRfc().render_command(), ["kramdown-rfc"])

    def test_draft_short_names(self) -> None:
        self.assertEqual(draft_short_name("draft-httpauth-payment-01.md"), "core")
        self.assertEqual(draft_short_name("draft-tempo-charge-00.md"), "tempo-charge")
        self.assertEqual(
            draft_short_name("draft-payment-intent-charge-00.md"), "intent-charge"
        )
        self.assertEqual(draft_short_name("draft-payment-discovery-01.md"), "discovery")

