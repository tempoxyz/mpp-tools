class StoredRenderTest(unittest.TestCase):
    """The stored renders are what kramdown-rfc renders today (needs kramdown-rfc)."""

    def test_stored_renders_match_kramdown_rfc(self) -> None:
        kramdown = RENDER.kramdown()
        if kramdown is None:
            self.skipTest(f"kramdown-rfc {KRAMDOWN_RFC_VERSION} is not installed")

        def check(entry: dict[str, str]) -> tuple[str, str | None]:
            markdown = entry["markdown"].encode("utf-8")
            try:
                return comparable_render(kramdown(markdown)), None
            except ValueError as error:
                return "", str(error)

        entries = list(RENDER.renders.items())
        with concurrent.futures.ThreadPoolExecutor(max_workers=8) as pool:
            results = list(pool.map(check, [entry for _, entry in entries]))
        for (key, entry), (xml, error) in zip(entries, results):
            with self.subTest(markdown=entry["markdown"][:60]):
                self.assertEqual(
                    hashlib.sha256(entry["markdown"].encode("utf-8")).hexdigest(), key
                )
                self.assertEqual(
                    (xml or None, error), (entry.get("xml"), entry.get("error"))
                )


