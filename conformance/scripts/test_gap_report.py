class FlowModeForcedStatusTest(unittest.TestCase):
    def test_forced_non_402_status_is_server_only_coverage(self) -> None:
        # flow_runner stops at the first non-402 response, before any adapter call.
        self.assertEqual(flow_mode({"name": "e", "path": "/e", "force_status": 500}), "raw_http")
        # A forced 402 carries no WWW-Authenticate either, so the adapter is never called.
        self.assertEqual(flow_mode({"name": "p", "path": "/p", "force_status": 402}), "raw_http")
        # The first request goes to challenge_path's case, so its forced status decides.
        forced = {"name": "f", "path": "/f", "force_status": 500}
        via = {"name": "v", "path": "/v", "challenge_path": "/f"}
        self.assertEqual(flow_mode(via, {"/f": forced, "/v": via}), "raw_http")
        self.assertEqual(flow_mode({"name": "o", "path": "/o", "challenge_path": "/v"}, {"/v": via}), "ordinary")
        # Nor does a no_payment, discovery or JSON-RPC case answer with a challenge.
        for flag in ("no_payment", "discovery", "json_rpc"):
            target = {"name": "t", "path": "/t", flag: True}
            via_flag = {"name": "w", "path": "/w", "challenge_path": "/t"}
            self.assertEqual(flow_mode(via_flag, {"/t": target, "/w": via_flag}), "raw_http")
        self.assertEqual(
            flow_mode({"name": "c", "path": "/c", "force_status": 500, "client_flow": True}),
            "client_flow",
        )

    def test_cases_the_server_never_answers_with_a_challenge(self) -> None:
        # The server looks cases up by pathname, so a query or fragment in path is a 404.
        self.assertEqual(flow_mode({"name": "q", "path": "/q?x=1"}), "raw_http")
        self.assertEqual(flow_mode({"name": "h", "path": "/h#f"}), "raw_http")
        # A missing challenge_path case fails in flow_runner before any adapter call.
        self.assertEqual(flow_mode({"name": "m", "path": "/m", "challenge_path": "/none"}, {}), "raw_http")

    def test_request_mpp_charge_rejects_never_reaches_the_adapter(self) -> None:
        # compliance-server.ts validates request with zod before it answers 402.
        full = {"amount": "1", "currency": "USD", "recipient": "m", "expires": "2099-01-01T00:00:00Z"}
        self.assertEqual(flow_mode({"name": "d", "path": "/d"}), "ordinary")
        self.assertEqual(flow_mode({"name": "f", "path": "/f", "request": full}), "ordinary")
        self.assertEqual(flow_mode({"name": "r", "path": "/r", "request": {**full, "resource": "/r"}}), "ordinary")
        missing = {k: v for k, v in full.items() if k != "expires"}
        self.assertEqual(flow_mode({"name": "m", "path": "/m", "request": missing}), "raw_http")
        self.assertEqual(flow_mode({"name": "n", "path": "/n", "request": {**full, "amount": 1}}), "raw_http")
        self.assertEqual(flow_mode({"name": "x", "path": "/x", "request": {**full, "resource": 2}}), "raw_http")

    def test_redirect_reaches_the_adapter_only_through_a_challenge_case(self) -> None:
        paid = {"name": "t", "path": "/t"}
        free = {"name": "n", "path": "/n", "no_payment": True}
        cases = {"/t": paid, "/n": free}
        self.assertEqual(flow_mode({"name": "r", "path": "/r", "redirect_to": "/t"}, cases), "ordinary")
        self.assertEqual(flow_mode({"name": "r", "path": "/r", "redirect_to": "/n"}, cases), "raw_http")
        self.assertEqual(flow_mode({"name": "r", "path": "/r", "redirect_to": "/gone"}, cases), "raw_http")
