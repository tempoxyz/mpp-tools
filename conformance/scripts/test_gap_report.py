# Every test reads drafts the way the report does, from kramdown-rfc's XML. CI has no
# kramdown-rfc, so the XML each test's Markdown renders to is stored, keyed by the
# Markdown's sha256, in testdata/gap_report_renders.json. With kramdown-rfc at
# KRAMDOWN_RFC_VERSION installed, StoredRenderTest renders every stored Markdown again
# and checks the stored XML still matches, so the expectations below are kramdown-rfc's
# own. To add renders for new or changed tests, run them with GAP_REPORT_REGENERATE=1.
RENDERS_PATH = Path(__file__).resolve().parent / "testdata" / "gap_report_renders.json"
REGENERATE = os.environ.get("GAP_REPORT_REGENERATE") == "1"


def comparable_render(document: str) -> str:
    """Drop the parts of kramdown-rfc's output that change between runs: today's date
    and the generator comment naming the Ruby version."""
    document = re.sub(
        r"<!-- generated by https://github.com/cabo/kramdown-rfc[^>]*-->\n?",
        "",
        document,
    )
    return re.sub(r"<date [^>]*/>", "", document)


class StoredRenders:
    """A renderer that answers from the stored kramdown-rfc renders (see RENDERS_PATH)."""

    def __init__(self) -> None:
        self.renders: dict[str, dict[str, str]] = {}
        if RENDERS_PATH.exists():
            self.renders = json.loads(RENDERS_PATH.read_text(encoding="utf-8"))[
                "renders"
            ]
        self.dirty = False
        self._kramdown: KramdownRfc | None | bool = False

    def kramdown(self) -> KramdownRfc | None:
        """kramdown-rfc at KRAMDOWN_RFC_VERSION, or None when it is not installed."""
        if self._kramdown is False:
            kramdown = KramdownRfc()
            try:
                kramdown.require(KRAMDOWN_RFC_VERSION)
                self._kramdown = kramdown
            except ValueError:
                self._kramdown = None
        return self._kramdown or None

    def __call__(self, markdown: bytes) -> str:
        key = hashlib.sha256(markdown).hexdigest()
        entry = self.renders.get(key)
        if entry is None:
            kramdown = self.kramdown() if REGENERATE else None
            if kramdown is None:
                raise AssertionError(
                    "no stored kramdown-rfc render for this Markdown; run the tests with "
                    f"GAP_REPORT_REGENERATE=1 and kramdown-rfc {KRAMDOWN_RFC_VERSION} installed"
                )
            try:
                entry = {"xml": comparable_render(kramdown(markdown))}
            except ValueError as error:
                entry = {"error": str(error)}  # kramdown-rfc refused this Markdown
            entry["markdown"] = markdown.decode("utf-8")
            self.renders[key] = entry
            self.dirty = True
        if "error" in entry:
            raise ValueError(entry["error"])
        return entry["xml"]

    def save(self) -> None:
        if not self.dirty:
            return
        RENDERS_PATH.parent.mkdir(exist_ok=True)
        RENDERS_PATH.write_text(
            json.dumps(
                {"kramdown_rfc": KRAMDOWN_RFC_VERSION, "renders": self.renders},
                indent=1,
                sort_keys=True,
            )
            + "\n",
            encoding="utf-8",
        )


RENDER = StoredRenders()


def tearDownModule() -> None:
    RENDER.save()


