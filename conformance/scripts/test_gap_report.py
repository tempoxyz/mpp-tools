class AttributeListDefinitionTest(unittest.TestCase):
    def test_ial_naming_a_definition_gets_its_id(self) -> None:
        # kramdown applies an ALD's attributes to every IAL that names it, resolving the
        # names after parsing, so a definition later in the draft applies too; referenced
        # IDs go first and the IAL's own ID wins (checked with kramdown-rfc). Definitions
        # in code or comments define nothing, and a definition line tags nothing itself.
        # A reference cycle crashes kramdown-rfc: see test_kramdown_failure_is_an_error.
        requirements, warnings, _ = read_draft(
            "Before MUST be.\n{: early}\n\n"
            "Own MUST win.\n{: early #req-tempo-charge-009}\n\n"
            "Nested MUST be.\n{: outer}\n\n"
            "Coded MUST not.\n{: coded}\n\n"
            "~~~\n{:coded: #req-tempo-charge-077}\n~~~\n\n"
            "<!-- {:hidden: #req-tempo-charge-088} -->\n\n"
            "Hidden MUST not.\n{: hidden}\n\n"
            "- {: late} Item MUST be.\n\n"
            "Defined MUST stay untagged.\n{:early: #req-tempo-charge-001}\n"
            "{:outer: inner .x}\n{:inner: #req-tempo-charge-002}\n"
            "{:late: #req-tempo-charge-003}\n"
        )
        self.assertEqual(
            [r.req_id for r in requirements],
            [
                "req-tempo-charge-001",
                "req-tempo-charge-009",
                "req-tempo-charge-002",
                None,
                None,
                "req-tempo-charge-003",
                None,
            ],
        )
        self.assertEqual(warnings, [])

    def test_consecutive_block_ials_all_apply_to_the_rule(self) -> None:
        # kramdown applies each IAL line right after a block to that block, so the last
        # ID any of them sets is the rule's: a later non-requirement ID revokes an earlier
        # requirement ID, whether set directly or through a definition. After a blank line
        # an IAL tags nothing. All checked with kramdown-rfc.
        requirements, warnings, _ = read_draft(
            "A MUST a.\n{: #req-tempo-charge-001}\n{: #note}\n\n"
            "B MUST b.\n{: #note}\n{: #req-tempo-charge-002}\n\n"
            "C MUST c.\n{: viadef}\n{: #other}\n\n"
            "D MUST d.\n{: #req-tempo-charge-004}\n{: .class}\n\n"
            "E MUST e.\n{: #req-tempo-charge-005}\n\n{: #note2}\n\n"
            "{:viadef: #req-tempo-charge-003}\n"
        )
        self.assertEqual(
            [r.req_id for r in requirements],
            [None, "req-tempo-charge-002", None, "req-tempo-charge-004", "req-tempo-charge-005"],
        )
        # The revoked requirement IDs tag nothing, and the report says so.
        self.assertEqual(
            [w.split(": ")[1].split(" is on no element")[0] for w in warnings],
            ["req-tempo-charge-001", "req-tempo-charge-003"],
        )

    def test_indented_definition_or_ial_in_a_paragraph_is_text(self) -> None:
        # ALD_START and IAL_BLOCK_START allow at most 3 leading spaces: indented 4 or more
        # inside a paragraph, the line is more paragraph text and defines nothing
        # (checked with kramdown-rfc). With 3 spaces it is a definition.
        requirements, _, _ = read_draft(
            "P MUST a.\n    {:ref: #req-tempo-charge-003}\n{: ref}\n\n"
            "Q MUST b.\n    {: #req-tempo-charge-006}\n\n"
            "R MUST c.\n   {:ref2: #req-tempo-charge-004}\nS MUST d.\n{: ref2}\n"
        )
        self.assertEqual(
            [r.req_id for r in requirements], [None, None, None, "req-tempo-charge-004"]
        )

    def test_many_definitions_read_in_linear_time(self) -> None:
        # The hand-written reader parsed attribute list definitions in quadratic time and
        # read a draft with any definition twice; kramdown-rfc resolves them now, and
        # reading its XML takes one pass however many there are.
        body = "".join(f"P{i} MUST a.\n{{: d{i}}}\n\n" for i in range(1, 400))
        body += "".join(f"{{:d{i}: #req-tempo-charge-{i:03}}}\n" for i in range(1, 400))
        start = time.monotonic()
        requirements, warnings, _ = read_draft(body)
        self.assertLess(time.monotonic() - start, 2)
        self.assertEqual(
            [r.req_id for r in requirements], [f"req-tempo-charge-{i:03}" for i in range(1, 400)]
        )
        self.assertEqual(warnings, [])

    def test_kramdown_failure_is_an_error(self) -> None:
        # A definition naming itself crashes kramdown-rfc 1.7.39; the report stops with an
        # error naming the draft rather than reporting the draft without its rules.
        with tempfile.TemporaryDirectory() as directory:
            specs = write_specs(
                Path(directory),
                {"specs/draft-tempo-charge-00.md": "# A\n\nLoop MUST stop.\n{: loop}\n\n{:loop: loop #req-tempo-charge-004}\n"},
            )
            with self.assertRaisesRegex(ValueError, r"specs/draft-tempo-charge-00\.md: kramdown-rfc failed"):
                extract_all(specs, RENDER)

    def test_empty_draft_name_component_is_malformed(self) -> None:
        requirements, warnings, _ = read_draft("P MUST a.\n{: #req-core--001}\n")
        self.assertEqual([r.id_problem for r in requirements], ["malformed"])
        self.assertTrue(any("does not match req-<draft>-<nnn>" in w for w in warnings))

    def test_empty_id_clears_the_requirement_id(self) -> None:
        # kramdown renders id="" as anchor="", replacing any earlier ID, whether from the
        # same IAL, a definition or an earlier IAL line (checked with kramdown-rfc).
        requirements, _, _ = read_draft(
            'A MUST a.\n{: #req-tempo-charge-001}\n{: id=""}\n\n'
            'B MUST b.\n{: d id=""}\n\n'
            'C MUST c.\n{: #req-tempo-charge-003 id=""}\n\n'
            "{:d: #req-tempo-charge-002}\n"
        )
        self.assertEqual([r.req_id for r in requirements], [None, None, None])

    def test_deep_definition_chain_resolves(self) -> None:
        # kramdown resolves a chain of definitions to any depth (the hand-written reader
        # stopped at 100).
        chain = "".join(f"{{:d{i}: d{i + 1}}}\n" for i in range(150))
        requirements, _, _ = read_draft(f"P MUST a.\n{{: d0}}\n\n{chain}{{:d150: #req-tempo-charge-001}}\n")
        self.assertEqual([r.req_id for r in requirements], ["req-tempo-charge-001"])

    def test_duplicate_check_sees_expanded_ids(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            specs = write_specs(
                Path(directory),
                {
                    "specs/draft-tempo-charge-00.md": "# A\n\nX MUST hold.\n{: reqdef}\n\n"
                    "Y MUST hold.\n{: #req-tempo-charge-001}\n\n{:reqdef: #req-tempo-charge-001}\n",
                },
            )
            requirements, warnings, _, _ = extract_all(specs, RENDER)
        self.assertEqual([r.id_problem for r in requirements], ["duplicate", "duplicate"])
        self.assertTrue(any("req-tempo-charge-001 already used" in w for w in warnings))


